  const htmlLanguages = {pt:'pt-BR',en:'en',es:'es'};
  const select = document.querySelector('#idioma');
  function content(selector, attribute, key) {
    return [...document.querySelectorAll(selector)].map(node => ({
      node, key:node.dataset[key], original:attribute ? node.getAttribute(attribute) : node.textContent, attribute
    }));
  }
  const nodes = [
    ...content('[data-i18n]', null, 'i18n'),
    ...content('[data-i18n-aria]', 'aria-label', 'i18nAria'),
    ...content('[data-i18n-alt]', 'alt', 'i18nAlt')
  ];
  const wa = content('[data-i18n-wa]', 'href', 'i18nWa');
  const internal = content('[data-i18n-link]', 'href', 'i18nLink');
  let language = 'pt';
  function text(key, fallback) {
    return messages[language]?.[key] ?? fallback;
  }
  window.orbyenIdioma = { text };

  function localizedHref(original) {
    if (language === 'pt') return original;
    const address = new URL(original, location.href);
    address.searchParams.set('lang', language);
    return address.href;
  }

  function apply(value) {
    language = Object.hasOwn(htmlLanguages, value) ? value : 'pt';
    document.documentElement.lang = htmlLanguages[language];
    for (const {node, key, original, attribute} of nodes) {
      const translated = text(key, original);
      if (attribute) node.setAttribute(attribute, translated);
      else node.textContent = translated;
    }
    for (const {node, key, original} of wa) {
      const message = text(key, null);
      const link = new URL(original);
      if (message) link.searchParams.set('text', message);
      node.href = message ? link.href : original;
    }
    for (const {node, original} of internal) node.setAttribute('href', localizedHref(original));
    select.value = language;
  }

  const query = new URL(location.href);
  apply(query.searchParams.get('lang'));
  select.closest('.language-picker').hidden = false;
  select.addEventListener('change', () => {
    document.dispatchEvent(new Event('orbyen:antes-idioma'));
    apply(select.value);
    const url = new URL(location.href);
    if (language === 'pt') url.searchParams.delete('lang');
    else url.searchParams.set('lang', language);
    history.replaceState(history.state, '', url);
    document.dispatchEvent(new Event('orbyen:idioma'));
  });
